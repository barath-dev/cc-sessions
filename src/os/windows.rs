pub fn executable_extensions() -> Vec<String> {
    let pathext = std::env::var("PATHEXT").unwrap_or_else(|_| ".EXE;.CMD;.BAT".into());
    pathext.split(';').filter(|e| !e.is_empty()).map(|e| e.to_lowercase()).collect()
}

fn env_dir(var: &str, fallback: &[&str]) -> PathBuf {
    match std::env::var_os(var) {
        Some(dir) if !dir.is_empty() => PathBuf::from(dir),
        _ => fallback.iter().fold(home(), |p, part| p.join(part)),
    }
}

