pub fn lock_exclusive(file: &File) -> std::io::Result<()> {
    // SAFETY: locks a handle we own; released when the file is closed.
    unsafe {
        let mut overlapped: OVERLAPPED = std::mem::zeroed();
        if LockFileEx(file.as_raw_handle() as HANDLE, LOCKFILE_EXCLUSIVE_LOCK, 0, u32::MAX, u32::MAX, &mut overlapped) != 0 {
            Ok(())
        } else {
            Err(std::io::Error::last_os_error())
        }
    }
}

/// Never uses a kill call: on Windows that would end the process being checked.
pub fn pid_alive(pid: u32) -> bool {
    if pid == 0 {
        return false;
    }
    // SAFETY: query-only handle, closed before returning.
    unsafe {
        let handle = OpenProcess(PROCESS_QUERY_LIMITED_INFORMATION, 0, pid);
        if handle.is_null() {
            // A process we may not open still exists.
            return GetLastError() == ERROR_ACCESS_DENIED;
        }
        let mut code = 0u32;
        let ok = GetExitCodeProcess(handle, &mut code);
        CloseHandle(handle);
        ok != 0 && code == STILL_ACTIVE
    }
}

/// When the process was created, in epoch milliseconds.
fn created_ms(pid: u32) -> Option<i64> {
    // SAFETY: query-only handle, closed before returning.
    unsafe {
        let handle = OpenProcess(PROCESS_QUERY_LIMITED_INFORMATION, 0, pid);
        if handle.is_null() {
            return None;
        }
        let mut times: [FILETIME; 4] = std::mem::zeroed();
        let [created, exited, kernel, user] = &mut times;
        let ok = GetProcessTimes(handle, created, exited, kernel, user);
        CloseHandle(handle);
        if ok == 0 {
            return None;
        }
        let ticks = ((times[0].dwHighDateTime as u64) << 32) | times[0].dwLowDateTime as u64;
        // FILETIME counts 100 ns steps from 1601-01-01.
        Some((ticks / 10_000) as i64 - 11_644_473_600_000)
    }
}

/// Make sure `pid` still is the session described by its `sessions/<pid>.json`
/// record: a process that started after the record was written is a reused pid.
pub fn verify_session_process(pid: u32, record: &Value) -> Result<()> {
    let Some(created) = created_ms(pid) else {
        return err("That process could not be inspected. Nothing was stopped.");
    };
    let started = record.get("startedAt").and_then(Value::as_i64).unwrap_or(0);
    if started > 0 && created > started + 5_000 {
        return err("The process id has been reused by another program. Nothing was stopped.");
    }
    Ok(())
}

pub fn parent_pid(pid: u32) -> Option<u32> {
    // SAFETY: snapshot handle is closed before returning; the entry is plain data.
    unsafe {
        let snapshot = CreateToolhelp32Snapshot(TH32CS_SNAPPROCESS, 0);
        if snapshot == INVALID_HANDLE_VALUE {
            return None;
        }
        let mut entry: PROCESSENTRY32W = std::mem::zeroed();
        entry.dwSize = std::mem::size_of::<PROCESSENTRY32W>() as u32;
        let mut found = None;
        let mut more = Process32FirstW(snapshot, &mut entry);
        while more != 0 {
            if entry.th32ProcessID == pid {
                found = Some(entry.th32ParentProcessID);
                break;
            }
            more = Process32NextW(snapshot, &mut entry);
        }
        CloseHandle(snapshot);
        found
    }
}

/// End the process and what it started. There is no gentler option here.
pub fn terminate(pid: u32) -> Result<()> {
    let mut cmd = Command::new("taskkill");
    cmd.args(["/PID", &pid.to_string(), "/T", "/F"]);
    let out = proc::run(&mut cmd, Duration::from_secs(15))?;
    if out.ok {
        Ok(())
    } else {
        err(format!("could not end pid {pid}: {}", out.last_line()))
    }
}

/// Start with no console of its own, so closing the terminal does not take it down.
pub fn detach(cmd: &mut Command) {
    // Windows hands every inheritable handle to a new process. Ours include the
    // pipes this command was started with, and a server holding those open would
    // keep whoever is reading them (a script, an installer) waiting forever.
    // SAFETY: only clears the inherit flag on this process's own standard handles.
    unsafe {
        for id in [STD_INPUT_HANDLE, STD_OUTPUT_HANDLE, STD_ERROR_HANDLE] {
            let handle = GetStdHandle(id);
            if !handle.is_null() && handle != INVALID_HANDLE_VALUE {
                SetHandleInformation(handle, HANDLE_FLAG_INHERIT, 0);
            }
        }
    }
    cmd.creation_flags(DETACHED_PROCESS | CREATE_NEW_PROCESS_GROUP);
}

/// The server has no console; without this each helper would flash a window.
pub fn quiet(cmd: &mut Command) {
    cmd.creation_flags(CREATE_NO_WINDOW);
}

