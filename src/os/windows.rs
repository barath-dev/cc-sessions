fn powershell(script: &str) -> Result<()> {
    let mut cmd = Command::new("powershell");
    cmd.args(["-NoProfile", "-NonInteractive", "-Command", script]);
    let out = proc::run(&mut cmd, Duration::from_secs(60))?;
    if out.ok {
        Ok(())
    } else {
        err(out.last_line())
    }
}

fn ps_quote(text: &str) -> String {
    format!("'{}'", text.replace('\'', "''"))
}

/// Make `name` start the program: a small launcher in the tool's `bin` folder,
/// which is added to the user's PATH.
pub fn install_command(name: &str, exe: &Path, previous: Option<&str>) -> Result<PathBuf> {
    let dir = bin_dir();
    fs::create_dir_all(&dir)?;
    let shim = dir.join(format!("{name}.cmd"));
    if let Some(existing) = which(name) {
        if existing != shim {
            return err(format!("{} is already a command on this PC. Pick another command name.", name));
        }
    }
    fs::write(&shim, format!("@echo off\r\n{COMMAND_MARK}\r\n\"{}\" %*\r\n", path_str(exe)))?;
    if let Some(old) = previous.filter(|old| !old.eq_ignore_ascii_case(name)) {
        let old_shim = dir.join(format!("{old}.cmd"));
        if fs::read_to_string(&old_shim).map(|t| t.contains(COMMAND_MARK)).unwrap_or(false) {
            fs::remove_file(&old_shim)?;
        }
    }
    // Tests install into a temporary folder and must not touch the real PATH.
    if std::env::var_os("CC_SESSIONS_SKIP_PATH").is_some() {
        return Ok(shim);
    }
    let bin = ps_quote(&path_str(&dir));
    powershell(&format!(
        "$p = [Environment]::GetEnvironmentVariable('Path', 'User'); \
         if (-not $p) {{ $p = '' }}; \
         if (($p -split ';') -notcontains {bin}) {{ \
           [Environment]::SetEnvironmentVariable('Path', (($p.TrimEnd(';') + ';' + {bin}).TrimStart(';')), 'User') }}"
    ))?;
    Ok(shim)
}

/// A Start-menu shortcut that starts the server and opens the page.
pub fn install_shortcut(exe: &Path) -> Result<PathBuf> {
    let link = env_dir("APPDATA", &["AppData", "Roaming"])
        .join("Microsoft")
        .join("Windows")
        .join("Start Menu")
        .join("Programs")
        .join("Claude Sessions.lnk");
    if let Some(parent) = link.parent() {
        fs::create_dir_all(parent)?;
    }
    let icon = store::state_file("icon.ico");
    fs::create_dir_all(store::state_dir())?;
    fs::write(&icon, include_bytes!("../../assets/icon.ico"))?;
    powershell(&format!(
        "$s = (New-Object -ComObject WScript.Shell).CreateShortcut({}); \
         $s.TargetPath = {}; $s.Arguments = 'ui'; $s.IconLocation = {}; $s.WindowStyle = 7; $s.Save()",
        ps_quote(&path_str(&link)),
        ps_quote(&path_str(exe)),
        ps_quote(&path_str(&icon))
    ))?;
    Ok(link)
}

