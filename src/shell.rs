//! Command text for each kind of shell. Pure string building, so every form can
//! be tested on every system; `os` decides which one a machine actually uses.

// Each system uses only its own forms.
#![allow(dead_code)]

use crate::tools::Tool;

/// One or more runs of a tool's command for an account, optionally in a folder.
#[derive(Debug, Clone, Default)]
pub struct Launch {
    pub tool: Tool,
    pub cwd: Option<String>,
    /// The account's config folder; `None` for the tool's default folder, which
    /// must run with the tool's variable (`CLAUDE_CONFIG_DIR`, `CODEX_HOME`) unset.
    pub config_dir: Option<String>,
    pub alias: Option<String>,
    /// Argument lists, run one after another.
    pub commands: Vec<Vec<String>>,
}

/// Quote for sh, bash and zsh.
pub fn sh_quote(text: &str) -> String {
    let safe = |c: char| c.is_ascii_alphanumeric() || "_@%+=:,./-".contains(c);
    if !text.is_empty() && text.chars().all(safe) {
        text.to_string()
    } else {
        format!("'{}'", text.replace('\'', "'\"'\"'"))
    }
}

fn ps_quote(text: &str) -> String {
    format!("'{}'", text.replace('\'', "''"))
}

/// `display` prefers the account's alias, for showing and copying. Otherwise the
/// account is spelled out, for running in a fresh terminal that may not have it.
pub fn posix(launch: &Launch, display: bool) -> String {
    let prefix = match (&launch.alias, &launch.config_dir) {
        (Some(alias), _) if display => alias.clone(),
        (_, None) if display => launch.tool.program().to_string(),
        (_, dir) => typed_prefix(launch.tool, dir.as_deref()),
    };
    let runs: Vec<String> = launch
        .commands
        .iter()
        .map(|args| format!("{prefix} {}", args.iter().map(|a| sh_quote(a)).collect::<Vec<_>>().join(" ")))
        .collect();
    let body = runs.join("; ");
    match &launch.cwd {
        Some(cwd) => format!("cd {} && {body}", sh_quote(cwd)),
        None => body,
    }
}

/// PowerShell form, shown in the Copy box on Windows.
pub fn powershell(launch: &Launch) -> String {
    let mut parts = Vec::new();
    if let Some(cwd) = &launch.cwd {
        parts.push(format!("Set-Location {}", ps_quote(cwd)));
    }
    let program = launch.tool.program();
    let prefix = match (&launch.alias, &launch.config_dir) {
        (Some(alias), _) => alias.clone(),
        (None, None) => program.to_string(),
        (None, Some(dir)) => {
            parts.push(format!("$env:{} = {}", launch.tool.env_var(), ps_quote(dir)));
            program.to_string()
        }
    };
    for args in &launch.commands {
        parts.push(format!("{prefix} {}", args.join(" ")));
    }
    parts.join("; ")
}

/// cmd.exe form, run with `cmd /k` in a new terminal window on Windows.
pub fn cmd(launch: &Launch) -> String {
    let mut parts = Vec::new();
    if let Some(cwd) = &launch.cwd {
        parts.push(format!("cd /d \"{cwd}\""));
    }
    parts.push(format!("set \"{}={}\"", launch.tool.env_var(), launch.config_dir.as_deref().unwrap_or("")));
    let mut text = parts.join(" && ");
    let program = launch.tool.program();
    let runs: Vec<String> = launch.commands.iter().map(|args| format!("{program} {}", args.join(" "))).collect();
    text.push_str(" && ");
    text.push_str(&runs.join(" & "));
    text
}

/// The shortcut command that starts one account.
#[derive(Debug, Clone, PartialEq)]
pub struct Shortcut {
    pub alias: String,
    pub tool: Tool,
    pub config_dir: Option<String>,
}

/// The tool's command with the account's folder spelled out, for sh.
fn posix_prefix(tool: Tool, config_dir: Option<&str>) -> String {
    match config_dir {
        None => format!("env -u {} {}", tool.env_var(), tool.program()),
        Some(dir) => format!("{}={} {}", tool.env_var(), sh_quote(dir), tool.program()),
    }
}

/// The same for a command typed into a terminal window. It starts with `env`:
/// a key pressed into the window as it is typed then breaks the command,
/// instead of the variable's name (`xCODEX_HOME=...`), which would run the
/// tool on the default account.
fn typed_prefix(tool: Tool, config_dir: Option<&str>) -> String {
    match config_dir {
        None => posix_prefix(tool, None),
        Some(dir) => format!("env {}", posix_prefix(tool, Some(dir))),
    }
}

/// One alias per account, valid in zsh and bash.
pub fn aliases_sh(shortcuts: &[Shortcut]) -> String {
    let mut out = String::from(
        "# Generated by paddock from its account registry.\n\
         # Do not edit: this file is rewritten whenever an account changes.\n",
    );
    for s in shortcuts {
        let inner = posix_prefix(s.tool, s.config_dir.as_deref());
        out.push_str(&format!("alias {}={}\n", s.alias, sh_quote(&inner)));
    }
    out
}

/// The same shortcuts as fish functions.
pub fn aliases_fish(shortcuts: &[Shortcut]) -> String {
    let mut out = String::from(
        "# Generated by paddock from its account registry.\n\
         # Do not edit: this file is rewritten whenever an account changes.\n",
    );
    for s in shortcuts {
        let (var, program) = (s.tool.env_var(), s.tool.program());
        let run = match &s.config_dir {
            None => format!("env -u {var} {program} $argv"),
            Some(dir) => format!("env {var}={} {program} $argv", sh_quote(dir)),
        };
        out.push_str(&format!("function {}\n    {run}\nend\n", s.alias));
    }
    out
}

/// A `claude-<name>.cmd` (or `codex-<name>.cmd`) launcher for one account on Windows.
pub fn cmd_shim(tool: Tool, config_dir: Option<&str>) -> String {
    format!(
        "@echo off\r\nrem Generated by paddock. Do not edit.\r\nsetlocal\r\nset \"{}={}\"\r\n{} %*\r\n",
        tool.env_var(),
        config_dir.unwrap_or(""),
        tool.program()
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    fn launch(config_dir: Option<&str>, alias: Option<&str>) -> Launch {
        Launch {
            tool: Tool::Claude,
            cwd: Some("/Users/me/My Project".into()),
            config_dir: config_dir.map(String::from),
            alias: alias.map(String::from),
            commands: vec![vec!["--resume".into(), "abc-123".into()]],
        }
    }

    #[test]
    fn quotes_only_when_needed() {
        assert_eq!(sh_quote("/Users/me/.claude-work"), "/Users/me/.claude-work");
        assert_eq!(sh_quote("my dir"), "'my dir'");
        assert_eq!(sh_quote("it's"), "'it'\"'\"'s'");
        assert_eq!(sh_quote(""), "''");
    }

    #[test]
    fn posix_display_uses_alias() {
        let text = posix(&launch(Some("/Users/me/.claude-work"), Some("claude-work")), true);
        assert_eq!(text, "cd '/Users/me/My Project' && claude-work --resume abc-123");
    }

    #[test]
    fn posix_exec_spells_the_account_out() {
        let text = posix(&launch(Some("/Users/me/.claude-work"), Some("claude-work")), false);
        assert_eq!(text, "cd '/Users/me/My Project' && env CLAUDE_CONFIG_DIR=/Users/me/.claude-work claude --resume abc-123");
    }

    #[test]
    fn default_account_runs_with_the_variable_unset() {
        assert_eq!(posix(&launch(None, None), true), "cd '/Users/me/My Project' && claude --resume abc-123");
        assert_eq!(
            posix(&launch(None, None), false),
            "cd '/Users/me/My Project' && env -u CLAUDE_CONFIG_DIR claude --resume abc-123"
        );
        assert!(cmd(&launch(None, None)).contains("set \"CLAUDE_CONFIG_DIR=\" && claude --resume abc-123"));
    }

    #[test]
    fn relogin_runs_logout_then_login() {
        let l = Launch {
            tool: Tool::Claude,
            cwd: None,
            config_dir: Some("/h/.claude-x".into()),
            alias: Some("claude-x".into()),
            commands: vec![vec!["auth".into(), "logout".into()], vec!["auth".into(), "login".into()]],
        };
        assert_eq!(
            posix(&l, false),
            "env CLAUDE_CONFIG_DIR=/h/.claude-x claude auth logout; env CLAUDE_CONFIG_DIR=/h/.claude-x claude auth login"
        );
        assert_eq!(cmd(&l), "set \"CLAUDE_CONFIG_DIR=/h/.claude-x\" && claude auth logout & claude auth login");
    }

    #[test]
    fn windows_forms() {
        let l = Launch {
            tool: Tool::Claude,
            cwd: Some(r"C:\Users\me\My Project".into()),
            config_dir: Some(r"C:\Users\me\.claude-work".into()),
            alias: None,
            commands: vec![vec!["--resume".into(), "abc-123".into()]],
        };
        assert_eq!(
            powershell(&l),
            r"Set-Location 'C:\Users\me\My Project'; $env:CLAUDE_CONFIG_DIR = 'C:\Users\me\.claude-work'; claude --resume abc-123"
        );
        assert_eq!(
            cmd(&l),
            "cd /d \"C:\\Users\\me\\My Project\" && set \"CLAUDE_CONFIG_DIR=C:\\Users\\me\\.claude-work\" && claude --resume abc-123"
        );
        let with_alias = Launch { alias: Some("claude-work".into()), ..l };
        assert_eq!(powershell(&with_alias), r"Set-Location 'C:\Users\me\My Project'; claude-work --resume abc-123");
    }

    #[test]
    fn codex_runs_with_its_own_variable() {
        let l = Launch {
            tool: Tool::Codex,
            cwd: Some("/w/app".into()),
            config_dir: Some("/h/.codex-work".into()),
            alias: Some("codex-work".into()),
            commands: vec![vec!["resume".into(), "019f".into()]],
        };
        assert_eq!(posix(&l, true), "cd /w/app && codex-work resume 019f");
        assert_eq!(posix(&l, false), "cd /w/app && env CODEX_HOME=/h/.codex-work codex resume 019f");
        assert_eq!(cmd(&l), "cd /d \"/w/app\" && set \"CODEX_HOME=/h/.codex-work\" && codex resume 019f");
        let default = Launch { config_dir: None, alias: None, ..l };
        assert_eq!(posix(&default, true), "cd /w/app && codex resume 019f");
        assert_eq!(posix(&default, false), "cd /w/app && env -u CODEX_HOME codex resume 019f");
        assert_eq!(powershell(&default), "Set-Location '/w/app'; codex resume 019f");
    }

    #[test]
    fn alias_files() {
        let shortcut = |alias: &str, tool, dir: Option<&str>| Shortcut { alias: alias.into(), tool, config_dir: dir.map(String::from) };
        let shortcuts = vec![
            shortcut("claude-work", Tool::Claude, Some("/Users/me/.claude-work")),
            shortcut("cl", Tool::Claude, None),
            shortcut("codex-work", Tool::Codex, Some("/Users/me/.codex-work")),
        ];
        let sh = aliases_sh(&shortcuts);
        assert!(sh.contains("alias claude-work='CLAUDE_CONFIG_DIR=/Users/me/.claude-work claude'\n"));
        assert!(sh.contains("alias cl='env -u CLAUDE_CONFIG_DIR claude'\n"));
        assert!(sh.contains("alias codex-work='CODEX_HOME=/Users/me/.codex-work codex'\n"));
        let fish = aliases_fish(&shortcuts);
        assert!(fish.contains("function claude-work\n    env CLAUDE_CONFIG_DIR=/Users/me/.claude-work claude $argv\nend\n"));
        assert!(fish.contains("function codex-work\n    env CODEX_HOME=/Users/me/.codex-work codex $argv\nend\n"));
        assert!(cmd_shim(Tool::Claude, Some(r"C:\Users\me\.claude-work")).contains("set \"CLAUDE_CONFIG_DIR=C:\\Users\\me\\.claude-work\"\r\nclaude %*"));
        assert!(cmd_shim(Tool::Codex, None).contains("set \"CODEX_HOME=\"\r\ncodex %*"));
    }
}
