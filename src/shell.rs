//! Command text for each kind of shell. Pure string building, so every form can
//! be tested on every system; `os` decides which one a machine actually uses.

// Each system uses only its own forms.
#![allow(dead_code)]

/// One or more `claude` invocations for an account, optionally in a folder.
#[derive(Debug, Clone, Default)]
pub struct Launch {
    pub cwd: Option<String>,
    /// The account's config folder; `None` for the default account, which must
    /// run with `CLAUDE_CONFIG_DIR` unset.
    pub config_dir: Option<String>,
    pub alias: Option<String>,
    /// Argument lists, run one after another.
    pub commands: Vec<Vec<String>>,
}

/// Quote for sh, bash and zsh.
pub fn sh_quote(text: &str) -> String {
    let safe = |c: char| c.is_ascii_alphanumeric() || "_@%+=:,./-".contains(c);
    if !text.is_empty() && text.chars().all(safe) {
        text.to_string()
    } else {
        format!("'{}'", text.replace('\'', "'\"'\"'"))
    }
}

fn ps_quote(text: &str) -> String {
    format!("'{}'", text.replace('\'', "''"))
}

/// `display` prefers the account's alias, for showing and copying. Otherwise the
/// account is spelled out, for running in a fresh terminal that may not have it.
pub fn posix(launch: &Launch, display: bool) -> String {
    let prefix = match (&launch.alias, &launch.config_dir) {
        (Some(alias), _) if display => alias.clone(),
        (_, None) if display => "claude".to_string(),
        (_, None) => "env -u CLAUDE_CONFIG_DIR claude".to_string(),
        (_, Some(dir)) => format!("CLAUDE_CONFIG_DIR={} claude", sh_quote(dir)),
    };
    let runs: Vec<String> = launch
        .commands
        .iter()
        .map(|args| format!("{prefix} {}", args.iter().map(|a| sh_quote(a)).collect::<Vec<_>>().join(" ")))
        .collect();
    let body = runs.join("; ");
    match &launch.cwd {
        Some(cwd) => format!("cd {} && {body}", sh_quote(cwd)),
        None => body,
    }
}

/// PowerShell form, shown in the Copy box on Windows.
pub fn powershell(launch: &Launch) -> String {
    let mut parts = Vec::new();
    if let Some(cwd) = &launch.cwd {
        parts.push(format!("Set-Location {}", ps_quote(cwd)));
    }
    let prefix = match (&launch.alias, &launch.config_dir) {
        (Some(alias), _) => alias.clone(),
        (None, None) => "claude".to_string(),
        (None, Some(dir)) => {
            parts.push(format!("$env:CLAUDE_CONFIG_DIR = {}", ps_quote(dir)));
            "claude".to_string()
        }
    };
    for args in &launch.commands {
        parts.push(format!("{prefix} {}", args.join(" ")));
    }
    parts.join("; ")
}

/// cmd.exe form, run with `cmd /k` in a new terminal window on Windows.
pub fn cmd(launch: &Launch) -> String {
    let mut parts = Vec::new();
    if let Some(cwd) = &launch.cwd {
        parts.push(format!("cd /d \"{cwd}\""));
    }
    parts.push(format!("set \"CLAUDE_CONFIG_DIR={}\"", launch.config_dir.as_deref().unwrap_or("")));
    let mut text = parts.join(" && ");
    let runs: Vec<String> = launch.commands.iter().map(|args| format!("claude {}", args.join(" "))).collect();
    text.push_str(" && ");
    text.push_str(&runs.join(" & "));
    text
}

/// One alias per account, valid in zsh and bash.
pub fn aliases_sh(accounts: &[(String, Option<String>)]) -> String {
    let mut out = String::from(
        "# Generated by cc-sessions from its account registry.\n\
         # Do not edit: this file is rewritten whenever an account changes.\n",
    );
    for (alias, config_dir) in accounts {
        let inner = match config_dir {
            None => "env -u CLAUDE_CONFIG_DIR claude".to_string(),
            Some(dir) => format!("CLAUDE_CONFIG_DIR={} claude", sh_quote(dir)),
        };
        out.push_str(&format!("alias {alias}={}\n", sh_quote(&inner)));
    }
    out
}

/// The same shortcuts as fish functions.
pub fn aliases_fish(accounts: &[(String, Option<String>)]) -> String {
    let mut out = String::from(
        "# Generated by cc-sessions from its account registry.\n\
         # Do not edit: this file is rewritten whenever an account changes.\n",
    );
    for (alias, config_dir) in accounts {
        let run = match config_dir {
            None => "env -u CLAUDE_CONFIG_DIR claude $argv".to_string(),
            Some(dir) => format!("env CLAUDE_CONFIG_DIR={} claude $argv", sh_quote(dir)),
        };
        out.push_str(&format!("function {alias}\n    {run}\nend\n"));
    }
    out
}

/// A `claude-<name>.cmd` launcher for one account on Windows.
pub fn cmd_shim(config_dir: Option<&str>) -> String {
    format!(
        "@echo off\r\nrem Generated by cc-sessions. Do not edit.\r\nsetlocal\r\nset \"CLAUDE_CONFIG_DIR={}\"\r\nclaude %*\r\n",
        config_dir.unwrap_or("")
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    fn launch(config_dir: Option<&str>, alias: Option<&str>) -> Launch {
        Launch {
            cwd: Some("/Users/me/My Project".into()),
            config_dir: config_dir.map(String::from),
            alias: alias.map(String::from),
            commands: vec![vec!["--resume".into(), "abc-123".into()]],
        }
    }

    #[test]
    fn quotes_only_when_needed() {
        assert_eq!(sh_quote("/Users/me/.claude-work"), "/Users/me/.claude-work");
        assert_eq!(sh_quote("my dir"), "'my dir'");
        assert_eq!(sh_quote("it's"), "'it'\"'\"'s'");
        assert_eq!(sh_quote(""), "''");
    }

    #[test]
    fn posix_display_uses_alias() {
        let text = posix(&launch(Some("/Users/me/.claude-work"), Some("claude-work")), true);
        assert_eq!(text, "cd '/Users/me/My Project' && claude-work --resume abc-123");
    }

    #[test]
    fn posix_exec_spells_the_account_out() {
        let text = posix(&launch(Some("/Users/me/.claude-work"), Some("claude-work")), false);
        assert_eq!(text, "cd '/Users/me/My Project' && CLAUDE_CONFIG_DIR=/Users/me/.claude-work claude --resume abc-123");
    }

    #[test]
    fn default_account_runs_with_the_variable_unset() {
        assert_eq!(posix(&launch(None, None), true), "cd '/Users/me/My Project' && claude --resume abc-123");
        assert_eq!(
            posix(&launch(None, None), false),
            "cd '/Users/me/My Project' && env -u CLAUDE_CONFIG_DIR claude --resume abc-123"
        );
        assert!(cmd(&launch(None, None)).contains("set \"CLAUDE_CONFIG_DIR=\" && claude --resume abc-123"));
    }

    #[test]
    fn relogin_runs_logout_then_login() {
        let l = Launch {
            cwd: None,
            config_dir: Some("/h/.claude-x".into()),
            alias: Some("claude-x".into()),
            commands: vec![vec!["auth".into(), "logout".into()], vec!["auth".into(), "login".into()]],
        };
        assert_eq!(
            posix(&l, false),
            "CLAUDE_CONFIG_DIR=/h/.claude-x claude auth logout; CLAUDE_CONFIG_DIR=/h/.claude-x claude auth login"
        );
        assert_eq!(cmd(&l), "set \"CLAUDE_CONFIG_DIR=/h/.claude-x\" && claude auth logout & claude auth login");
    }

    #[test]
    fn windows_forms() {
        let l = Launch {
            cwd: Some(r"C:\Users\me\My Project".into()),
            config_dir: Some(r"C:\Users\me\.claude-work".into()),
            alias: None,
            commands: vec![vec!["--resume".into(), "abc-123".into()]],
        };
        assert_eq!(
            powershell(&l),
            r"Set-Location 'C:\Users\me\My Project'; $env:CLAUDE_CONFIG_DIR = 'C:\Users\me\.claude-work'; claude --resume abc-123"
        );
        assert_eq!(
            cmd(&l),
            "cd /d \"C:\\Users\\me\\My Project\" && set \"CLAUDE_CONFIG_DIR=C:\\Users\\me\\.claude-work\" && claude --resume abc-123"
        );
        let with_alias = Launch { alias: Some("claude-work".into()), ..l };
        assert_eq!(powershell(&with_alias), r"Set-Location 'C:\Users\me\My Project'; claude-work --resume abc-123");
    }

    #[test]
    fn alias_files() {
        let accounts = vec![
            ("claude-work".to_string(), Some("/Users/me/.claude-work".to_string())),
            ("cl".to_string(), None),
        ];
        let sh = aliases_sh(&accounts);
        assert!(sh.contains("alias claude-work='CLAUDE_CONFIG_DIR=/Users/me/.claude-work claude'\n"));
        assert!(sh.contains("alias cl='env -u CLAUDE_CONFIG_DIR claude'\n"));
        let fish = aliases_fish(&accounts);
        assert!(fish.contains("function claude-work\n    env CLAUDE_CONFIG_DIR=/Users/me/.claude-work claude $argv\nend\n"));
        assert!(cmd_shim(Some(r"C:\Users\me\.claude-work")).contains("set \"CLAUDE_CONFIG_DIR=C:\\Users\\me\\.claude-work\"\r\nclaude %*"));
    }
}
